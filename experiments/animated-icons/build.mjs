// Builds animation-ready SVG markup from packages/core/svgs and a self-contained
// preview page. Run: node experiments/animated-icons/build.mjs
//
// "Animation-ready" means three small, static transforms that any framework
// package's codegen could apply the same way:
//   1. children wrapped in <g data-solar-root> (whole-icon transforms)
//   2. every shape gets pathLength="1" (resolution-independent draw-in/out)
//   3. every shape gets data-part="<role>" from PARTS (per-part animations)

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const svgsDir = join(here, '../../packages/core/svgs')
const STYLE = process.env.STYLE ?? 'Linear'

/** Part roles per icon, in document order of the shapes. */
const PARTS = {
    'chat-round-warning': ['bubble', 'bar', 'dot'],
    'restart-circle': ['ring', 'arrow'],
    'chat-round-unread': ['badge', 'bubble'],
    'chat-square-arrow': ['bubble', 'arrow', 'arrow', 'bubble'],
    'chat-round-like': ['bubble', 'heart'],
    inbox: ['box', 'tray'],
    'user-speak-rounded': ['head', 'body', 'wave', 'wave'],
    list: ['row', 'row', 'row'],
    'user-circle': ['head', 'ring', 'body'],
    'chat-round': ['bubble'],
    'star-circle': ['ring', 'star'],
    'pen-new-round': ['pen', 'arc'],
    'pen-2': ['base', 'pen'],
    'chat-round-quote': ['bubble', 'quote', 'quote'],
    'chat-round-question-mark': ['bubble', 'hook', 'dot'],
    'chat-round-money': ['bubble', 'sign'],
    translation: ['outer', 'inner', 'core'],
    'link-circle': ['left', 'right'],
    'letter-unread': ['envelope', 'flap', 'badge'],
    'chat-round-code': ['bubble', 'right', 'slash', 'left'],
    'chat-round-dots': ['bubble', 'dot', 'dot', 'dot'],
    'chat-round-line': ['bubble', 'line', 'line'],
    fire: ['outer', 'inner'],
    'mention-circle': ['at', 'ring'],
}

/** Compound paths that must become separate shapes to animate independently. */
const SPLIT = new Set(['chat-round-dots'])

/** Extra icons used by the transition demos. */
const EXTRA = [
    'chat-round-check',
    'chat-round-close',
    'chat-round-add',
    'chat-round-call',
    'chat-round-video',
    'letter',
    'letter-opened',
    'inbox-in',
    'inbox-out',
]

/** Duotone samples for the layer demo, keyed as `name@LineDuotone`. */
const DUOTONE = ['chat-round-line', 'letter-unread', 'inbox', 'chat-round-dots']

function indexStyle(style) {
    const map = new Map()
    for (const category of readdirSync(svgsDir)) {
        const dir = join(svgsDir, category, style)
        if (!existsSync(dir)) continue
        for (const file of readdirSync(dir)) map.set(file.replace(/\.svg$/, ''), join(dir, file))
    }
    return map
}

const index = indexStyle(STYLE)
const duotoneIndex = indexStyle('LineDuotone')

const SHAPE = /<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*?)\/>/g

function splitCompound(attrs) {
    const d = /\bd="([^"]+)"/.exec(attrs)[1]
    return d
        .split(/(?=M)/)
        .map(segment => attrs.replace(/\bd="[^"]+"/, `d="${segment.trim()}"`))
}

function transform(name, raw) {
    const roles = PARTS[name] ?? []
    const body = raw
        .replace(/^[\s\S]*?<svg[^>]*>/, '')
        .replace(/<\/svg>\s*$/, '')
        .replace(/(stroke|fill)="#1C274C"/g, '$1="currentColor"')

    let shapeIndex = 0
    const shapes = body.replace(SHAPE, (_m, tag, attrs) => {
        const pieces = tag === 'path' && SPLIT.has(name) ? splitCompound(attrs) : [attrs]
        return pieces
            .map(pieceAttrs => {
                const role = roles[shapeIndex++] ?? 'part'
                return `<${tag} data-part="${role}" pathLength="1"${pieceAttrs}/>`
            })
            .join('')
    })

    return (
        `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" ` +
        `class="solar solar-${name}" data-solar-icon="${name}">` +
        `<g data-solar-root="">${shapes.replace(/\n\s*/g, '')}</g></svg>`
    )
}

const names = [...Object.keys(PARTS), ...EXTRA]
const icons = {}
for (const name of names) {
    const file = index.get(name)
    if (!file) throw new Error(`Icon not found in ${STYLE}: ${name}`)
    icons[name] = transform(name, readFileSync(file, 'utf8'))
}
for (const name of DUOTONE) {
    // Duotone shape order differs from Linear, so parts stay generic here.
    icons[`${name}@LineDuotone`] = transform(`${name}@duotone`, readFileSync(duotoneIndex.get(name), 'utf8'))
}

writeFileSync(
    join(here, 'icons.js'),
    `// Generated by build.mjs (${STYLE}). Do not edit.\nexport const icons = ${JSON.stringify(icons, null, 4)}\n`
)

// Self-contained preview: inline the ES modules into one <script type="module">
// so the page opens straight from disk (file:// blocks cross-file module imports).
const stripModule = source =>
    source
        .replace(/^import[\s\S]*?from\s+['"][^'"]+['"]\s*;?\s*$/gm, '')
        .replace(/^export\s+(?=(const|function|async|let|class)\b)/gm, '')

const inlined = ['icons.js', 'solar-animate.js', 'presets.js', 'demo.js']
    .map(file => `// ---- ${file}\n${stripModule(readFileSync(join(here, file), 'utf8'))}`)
    .join('\n')

const html = readFileSync(join(here, 'index.html'), 'utf8').replace(
    /<script type="module" src="\.\/demo\.js"><\/script>/,
    () => `<script type="module">\n${inlined}\n</script>`
)
writeFileSync(join(here, 'preview.html'), html)

console.log(`Built ${names.length} icons (${STYLE}) -> icons.js, preview.html`)
